// Recurring event expansion. RRULEs are evaluated in the event's own timezone
// (wall clock), so "every Monday 09:00 Asia/Kolkata" stays 09:00 local even for
// zones with daylight-saving transitions.
import * as rruleNs from 'rrule'
import { fromWallClock, toWallClock } from './time.ts'

// Vite resolves rrule's ESM build (named exports); Deno loads the CJS build,
// where the exports sit on `default`. Support both.
type RRuleModule = typeof import('rrule')
const RRule: RRuleModule['RRule'] =
  (rruleNs as RRuleModule).RRule ?? (Reflect.get(rruleNs, 'default') as RRuleModule).RRule

export interface RecurringSource {
  id: string
  start_at: string
  end_at: string
  timezone: string
  rrule: string | null
  exdates?: string[] | null
}

export interface Occurrence {
  start: Date
  end: Date
  /** start of the occurrence as generated by the rule (identity of the instance) */
  originalStart: Date
}

export function parseRule(rule: string, dtstartWall: Date) {
  const body = rule.replace(/^RRULE:/i, '')
  return new RRule({ ...RRule.parseString(body), dtstart: dtstartWall })
}

/**
 * Expand a recurring master into concrete occurrences overlapping [from, to).
 * `overridden` holds original_start ISO strings of exception rows; those
 * instances are skipped because the exception row renders instead.
 */
export function expandOccurrences(
  src: RecurringSource,
  from: Date,
  to: Date,
  overridden: Set<string> = new Set(),
  maxCount = 1000,
): Occurrence[] {
  if (!src.rrule) return []
  const start = new Date(src.start_at)
  const durationMs = new Date(src.end_at).getTime() - start.getTime()
  const rule = parseRule(src.rrule, toWallClock(start, src.timezone))
  const ex = new Set((src.exdates ?? []).map((d) => new Date(d).getTime()))

  // widen the window by the duration so events that started before `from` but are still running are included
  const wallFrom = toWallClock(new Date(from.getTime() - durationMs), src.timezone)
  const wallTo = toWallClock(to, src.timezone)
  const out: Occurrence[] = []
  for (const wall of rule.between(wallFrom, wallTo, true)) {
    const s = fromWallClock(wall, src.timezone)
    if (ex.has(s.getTime()) || overridden.has(s.toISOString())) continue
    const e = new Date(s.getTime() + durationMs)
    if (e.getTime() <= from.getTime() && durationMs > 0) continue
    if (s.getTime() >= to.getTime()) continue
    out.push({ start: s, end: e, originalStart: s })
    if (out.length >= maxCount) break
  }
  return out
}

/** RRULE UNTIL value (wall clock) that ends the series just before `occurrence`. */
export function untilBefore(occurrence: Date, tz: string): string {
  const wall = new Date(toWallClock(occurrence, tz).getTime() - 1000)
  return wall.toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '')
}

/** Replace/insert UNTIL (and drop COUNT) in a rule string. */
export function withUntil(rule: string, until: string): string {
  const parts = rule
    .replace(/^RRULE:/i, '')
    .split(';')
    .filter((p) => p && !/^(UNTIL|COUNT)=/i.test(p))
  parts.push(`UNTIL=${until}`)
  return parts.join(';')
}

export type RepeatPreset = 'none' | 'daily' | 'weekdays' | 'weekly' | 'biweekly' | 'monthly' | 'yearly' | 'custom'

const WEEKDAY_CODES = ['SU', 'MO', 'TU', 'WE', 'TH', 'FR', 'SA']

export function presetToRule(preset: RepeatPreset, start: Date, tz: string): string | null {
  const dow = WEEKDAY_CODES[toWallClock(start, tz).getUTCDay()]
  switch (preset) {
    case 'daily': return 'FREQ=DAILY'
    case 'weekdays': return 'FREQ=WEEKLY;BYDAY=MO,TU,WE,TH,FR'
    case 'weekly': return `FREQ=WEEKLY;BYDAY=${dow}`
    case 'biweekly': return `FREQ=WEEKLY;INTERVAL=2;BYDAY=${dow}`
    case 'monthly': return 'FREQ=MONTHLY'
    case 'yearly': return 'FREQ=YEARLY'
    default: return null
  }
}

export function describeRule(rule: string | null): string {
  if (!rule) return 'Does not repeat'
  try {
    return parseRule(rule, new Date()).toText()
  } catch {
    return 'Custom recurrence'
  }
}

export function isValidRule(rule: string): boolean {
  try {
    const r = parseRule(rule, new Date(Date.UTC(2026, 0, 1)))
    return r.all((_, i) => i < 1).length >= 0
  } catch {
    return false
  }
}
